"""Turn dumped notes into a connected brain.

Two passes, deliberately split by cost:

1. rebuild_indexes()  — DETERMINISTIC, FREE. Writes a Map-of-Content per zone (`_index.md`)
   and a root `MAP.md`, each wiki-linking every note it covers. This alone crushes the
   "92% orphan" problem: an orphan is a note nothing links TO, and now its zone index does.

2. digest_note(rel)   — ONE cheap Haiku call. Reads a note, returns {summary, type, tags,
   links}, then enriches the note's frontmatter and appends a `## Connections` section with
   [[links]] validated against notes that actually exist. Batched (a few per run) so it never
   spends a whole 5-hour subscription window in one burst.

Together: imports become understandable (summaries/tags), trackable (a `digested:` marker +
progress notices), and connected (indexes + semantic links). The worker owns the vault, so
these housekeeping writes are made with approved=True — the model only *suggests* metadata.
"""
import json
import logging
from datetime import date, datetime

import frontmatter

from ..config import settings
from ..memory import vault as V

log = logging.getLogger("kioku.digest")

# Zones Kioku digests/indexes. Its own system + generated dirs are left alone.
_SKIP_DIRS = {"system", "_reports", ".obsidian", "_import"}
_INDEX_NAMES = {"_index.md", "map.md"}


def _norm(rel: str) -> str:
    return rel.replace("\\", "/")            # normalize Windows separators to posix


def _is_index(rel: str) -> bool:
    name = _norm(rel).split("/")[-1].lower()
    return name in _INDEX_NAMES or name.endswith("-index.md")


def _zone(rel: str) -> str:
    rel = _norm(rel)
    return rel.split("/")[0] if "/" in rel else ""


def _covered(rel: str) -> bool:
    """Notes we manage: not in a skipped zone, not an index note itself."""
    return _zone(rel) not in _SKIP_DIRS and not _is_index(rel)


def _summary_of(rel: str) -> str:
    try:
        post = frontmatter.loads(V.read(rel))
        s = post.metadata.get("summary")
        if s:
            return str(s)[:140]
        # fall back to first non-empty prose line
        for line in post.content.splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                return line[:140]
    except Exception:  # noqa: BLE001
        pass
    return ""


# ---------------------------------------------------------------- structural (free) ----
def rebuild_indexes() -> dict:
    """(Re)write one `_index.md` per zone and a root `MAP.md`. Deterministic, no model calls."""
    from pathlib import Path
    files = [str(p.relative_to(V.VAULT)) for p in V._md_files()]
    by_zone: dict[str, list[str]] = {}
    for rel in files:
        if not _covered(rel):
            continue
        by_zone.setdefault(_zone(rel) or "root", []).append(rel)

    # Each zone index gets a UNIQUE stem (`<zone>-index`) so [[wikilinks]] resolve by basename
    # (Obsidian + our audit both match on stem, not path). Root notes use `_index`.
    def _index_stem(zone: str) -> str:
        return "_index" if zone == "root" else f"{zone}-index"

    written = 0
    for zone, rels in sorted(by_zone.items()):
        if not rels:
            continue
        lines = [f"# {zone} — index", "",
                 f"_Auto-maintained map of {len(rels)} notes. Regenerated by Kioku._", ""]
        for rel in sorted(rels):
            stem = Path(rel).stem
            summ = _summary_of(rel)
            lines.append(f"- [[{stem}]]" + (f" — {summ}" if summ else ""))
        stem = _index_stem(zone)
        target = f"{stem}.md" if zone == "root" else f"{zone}/{stem}.md"
        V.write(target, "\n".join(lines) + "\n", approved=True)
        written += 1

    # Root MAP links every zone index by its unique stem → the whole tree hangs off one note.
    maplines = ["# MAP — Kioku's brain", "",
                f"_Generated {date.today().isoformat()}. Entry point to every zone._", ""]
    for zone in sorted(by_zone):
        maplines.append(f"- **{zone}** → [[{_index_stem(zone)}]] ({len(by_zone[zone])} notes)")
    V.write("MAP.md", "\n".join(maplines) + "\n", approved=True)
    return {"zones": written, "notes": sum(len(v) for v in by_zone.values())}


# ---------------------------------------------------------------- digestion (cheap model) ----
def find_undigested(limit: int = 6) -> list[str]:
    """Notes we manage that lack a `digested: true` marker. Inbox + freshly-imported first."""
    pending: list[str] = []
    for p in V._md_files():
        rel = str(p.relative_to(V.VAULT))
        if not _covered(rel):
            continue
        try:
            if frontmatter.loads(V.read(rel)).metadata.get("digested"):
                continue
        except Exception:  # noqa: BLE001
            pass
        pending.append(_norm(rel))
    # process inbox/ and reference/imported/ before the rest
    pending.sort(key=lambda r: (0 if r.startswith(("inbox/", "reference/imported/")) else 1, r))
    return pending[:limit]


_DIGEST_SYS = (
    "You organize a personal knowledge vault. Given ONE note and a list of EXISTING note "
    "titles, return ONLY JSON:\n"
    '{"summary": "<=20 words, what this note is",'
    ' "type": "conversation|project|person|note|reference|cv|financial|idea|task",'
    ' "tags": ["3-6 lowercase-kebab topics"],'
    ' "links": ["<=5 EXISTING titles from the provided list that are genuinely related"],'
    ' "claims": ["0-5 DURABLE, checkable facts stated in the note (about the user or their'
    ' world) — atomic sentences, no opinions or ephemeral chatter"],'
    ' "people": [{"name":"a real person named in the note","context":"<=12 words: who they'
    ' are / relationship / what they want"}]}\n'
    "Only use titles from the list for links. Only real named people (skip if none). No prose, no code fences."
)


async def _classify(rel: str, body: str, candidate_titles: list[str]) -> dict | None:
    from claude_agent_sdk import query, ClaudeAgentOptions
    opts = ClaudeAgentOptions(model=settings.model_triage, system_prompt=_DIGEST_SYS, max_turns=1)
    prompt = (f"NOTE ({rel}):\n{body[:3000]}\n\n"
              f"EXISTING TITLES:\n{', '.join(candidate_titles[:200])}")
    text_buf, result_buf = "", ""
    try:
        async for m in query(prompt=prompt, options=opts):
            content = getattr(m, "content", None)
            if isinstance(content, list):
                for blk in content:
                    t = getattr(blk, "text", None)
                    if isinstance(t, str):
                        text_buf += t
            res = getattr(m, "result", None)
            if isinstance(res, str):
                result_buf += res
    except Exception as e:  # noqa: BLE001  — the model call itself failed (usually a usage limit)
        log.warning("digest classify: query failed for %s — %s: %s", rel, type(e).__name__, str(e)[:160])
        return None
    # Use the assembled TEXT, falling back to result — NOT both. Concatenating both doubled the JSON
    # (TextBlock says it once, ResultMessage.result repeats it), so a first-brace..last-brace slice
    # spanned two copies + the ```json fence between them and never parsed. That was the whole
    # "0 digested" stall — Haiku's JSON was fine all along.
    buf = (text_buf or result_buf).strip()
    if not buf:
        log.warning("digest classify: empty response for %s (likely a usage limit / refusal)", rel)
        return None
    i = buf.find("{")
    if i == -1:
        log.warning("digest classify: no JSON object for %s — head: %s", rel, buf[:160])
        return None
    try:
        # raw_decode parses the FIRST JSON object and ignores anything after it (a ```json fence, a
        # duplicated copy, trailing prose) — robust to how the model wraps the answer.
        data, _ = json.JSONDecoder().raw_decode(buf[i:])
        return data if isinstance(data, dict) else None
    except Exception:  # noqa: BLE001
        log.warning("digest classify: unparseable JSON for %s — head: %s", rel, buf[:160])
        return None


async def digest_note(rel: str) -> dict:
    """Enrich one note with summary/type/tags + validated [[Connections]]. Marks it digested."""
    from pathlib import Path
    post = frontmatter.loads(V.read(rel))
    if post.metadata.get("digested"):
        return {"path": rel, "skipped": "already digested"}

    titles = V.note_titles()                       # {stem_lower: relpath}
    self_stem = Path(rel).stem.lower()
    candidates = [V.VAULT.joinpath(p).stem for s, p in titles.items() if s != self_stem]

    meta = await _classify(rel, post.content, candidates)
    if not meta:
        return {"path": rel, "skipped": "classify failed"}

    # validate suggested links against notes that actually exist (case-insensitive)
    valid_links = []
    for link in (meta.get("links") or [])[:5]:
        key = str(link).strip().lower()
        if key in titles and key != self_stem and link not in valid_links:
            valid_links.append(str(link).strip())

    post.metadata["type"] = post.metadata.get("type") or meta.get("type") or "note"
    post.metadata["summary"] = str(meta.get("summary", ""))[:200]
    if meta.get("tags"):
        post.metadata["tags"] = [str(t).strip().lower() for t in meta["tags"]][:6]
    post.metadata["digested"] = True
    post.metadata["digested_at"] = datetime.now().isoformat(timespec="seconds")

    body = post.content
    if valid_links and "## Connections" not in body:
        body = body.rstrip() + "\n\n## Connections\n" + \
            "\n".join(f"- [[{name}]]" for name in valid_links) + "\n"
    post.content = body

    V.write(rel, frontmatter.dumps(post) + "\n", approved=True)

    # Populate the claim ledger from the same call (near-free). Never fatal.
    n_claims = 0
    try:
        from ..memory import claims
        stmts = [str(s) for s in (meta.get("claims") or []) if str(s).strip()][:5]
        n_claims = claims.replace_claims_sync(rel, stmts)
    except Exception:  # noqa: BLE001
        pass

    # Populate the people CRM from the same call. Never fatal.
    n_people = 0
    try:
        from ..memory import people
        for person in (meta.get("people") or [])[:8]:
            nm = str(person.get("name", "")).strip() if isinstance(person, dict) else ""
            if nm:
                people.upsert_person_sync(nm, str(person.get("context", "")), rel)
                n_people += 1
    except Exception:  # noqa: BLE001
        pass

    return {"path": rel, "type": post.metadata["type"], "links": len(valid_links),
            "claims": n_claims, "people": n_people, "tags": post.metadata.get("tags", [])}
